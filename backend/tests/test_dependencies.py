"""The dependency files stay in step: every library declared in pyproject.toml is pinned in requirements.txt.

If this fails after you added or changed a library, run `python scripts/dev.py lock` from the repo root and commit
pyproject.toml, uv.lock and requirements.txt together."""
import re
import tomllib
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]


def _name(spec: str) -> str:
    return re.split(r"[\s\[<>=!~;]", spec.strip(), maxsplit=1)[0].lower().replace("_", "-")


def _pinned() -> dict:
    pins = {}
    for line in (BACKEND / "requirements.txt").read_text().splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==(\S+)", line)
        if m:
            pins[m.group(1).lower().replace("_", "-")] = m.group(2)
    return pins


def test_every_declared_library_is_pinned():
    project = tomllib.loads((BACKEND / "pyproject.toml").read_text())["project"]
    declared = {_name(s) for s in project["dependencies"]} | {_name(s) for group in project.get("optional-dependencies", {}).values() for s in group}
    missing = sorted(declared - set(_pinned()))
    assert not missing, f"Not in requirements.txt: {missing}. Run `python scripts/dev.py lock`."


def test_requirements_file_is_generated_not_hand_edited():
    text = (BACKEND / "requirements.txt").read_text()
    assert text.startswith("# GENERATED from pyproject.toml"), "requirements.txt is generated by `python scripts/dev.py lock`"
    assert all("==" in l for l in text.splitlines() if l and not l.startswith((" ", "#"))), "every requirement must be an exact pin"
    assert (BACKEND / "uv.lock").exists()
