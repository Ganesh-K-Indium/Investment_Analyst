"""The dependency files stay in step: every library declared in pyproject.toml is pinned in requirements.txt, and each
optional OCR engine (`ocr-<engine>` extra) in requirements-ocr/<engine>.txt.

If this fails after you added or changed a library, run `python scripts/dev.py lock` from the repo root and commit
pyproject.toml, uv.lock, requirements.txt and requirements-ocr/ together."""
import re
import tomllib
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
OCR_PREFIX = "ocr-"


def _name(spec: str) -> str:
    return re.split(r"[\s\[<>=!~;]", spec.strip(), maxsplit=1)[0].lower().replace("_", "-")


def _pinned(path: Path) -> dict:
    pins = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==(\S+)", line)
        if m:
            pins[m.group(1).lower().replace("_", "-")] = m.group(2)
    return pins


def _project() -> dict:
    return tomllib.loads((BACKEND / "pyproject.toml").read_text())["project"]


def test_every_declared_library_is_pinned():
    project = _project()
    extras = {k: v for k, v in project.get("optional-dependencies", {}).items() if not k.startswith(OCR_PREFIX)}
    declared = {_name(s) for s in project["dependencies"]} | {_name(s) for group in extras.values() for s in group}
    missing = sorted(declared - set(_pinned(BACKEND / "requirements.txt")))
    assert not missing, f"Not in requirements.txt: {missing}. Run `python scripts/dev.py lock`."


def test_every_ocr_engine_is_pinned_in_its_own_file():
    base = _pinned(BACKEND / "requirements.txt")
    engines = {k[len(OCR_PREFIX):]: v for k, v in _project().get("optional-dependencies", {}).items() if k.startswith(OCR_PREFIX)}
    assert engines, "expected the optional OCR engines as ocr-<engine> extras"
    for engine, specs in engines.items():
        path = BACKEND / "requirements-ocr" / f"{engine}.txt"
        assert path.exists(), f"{path.name} is missing. Run `python scripts/dev.py lock`."
        text = path.read_text()
        assert text.startswith("# GENERATED"), f"{path.name} is generated by `python scripts/dev.py lock`"
        assert "-r ../requirements.txt" in text.splitlines(), f"{path.name} must build on the base pins"
        pins = _pinned(path)
        missing = sorted({_name(s) for s in specs} - set(pins) - set(base))
        assert not missing, f"Not in {path.name}: {missing}. Run `python scripts/dev.py lock`."
        clash = sorted(n for n in set(pins) & set(base) if pins[n] != base[n])
        assert not clash, f"{path.name} pins {clash} differently from requirements.txt. Run `python scripts/dev.py lock`."


def test_requirements_file_is_generated_not_hand_edited():
    text = (BACKEND / "requirements.txt").read_text()
    assert text.startswith("# GENERATED from pyproject.toml"), "requirements.txt is generated by `python scripts/dev.py lock`"
    assert all("==" in l for l in text.splitlines() if l and not l.startswith((" ", "#"))), "every requirement must be an exact pin"
    assert (BACKEND / "uv.lock").exists()
